# 有代价的道具：`costs` 里一律写**正数**，语义由"它在 costs 里"决定（RunSession.WriteBonus 传 −1）


def read_text(path):
    """返回 (文本, 是否有 BOM)。**显式 UTF-8**，绝不走 PowerShell。"""
    with open(path, "rb") as f:
        raw = f.read()
    bom = raw.startswith(b"\xef\xbb\xbf")
    return raw[3:].decode("utf-8") if bom else raw.decode("utf-8"), bom


def write_text(path, text, bom):
    with open(path, "wb") as f:
        if bom:
            f.write(b"\xef\xbb\xbf")
        f.write(text.encode("utf-8"))


def main(argv):
    dry = "--dry-run" in argv
    text, bom = read_text(ITEMS)
    table = json.loads(text)                            # 先证明盘上的表是好的
    have = [it["id"] for it in table["items"]]

    # ── ① 描述：逐行替换该 id 所在块里的 `"desc": "..."` ──
    lines = text.split("\n")
    changed = 0
    missing = []
    for iid, desc in DESC.items():
        if iid not in have:
            missing.append(iid)
            continue
        # 找到 `"id": "<iid>"` 那一行，然后从那里往下找第一条 "desc":
        start = None
        for i, ln in enumerate(lines):
            if '"id": "%s"' % iid in ln:
                start = i
                break
        if start is None:
            missing.append(iid + "(行没找到)")
            continue
        done = False
        for j in range(start, min(start + 30, len(lines))):
            if '"desc"' in lines[j]:
                indent = lines[j][:len(lines[j]) - len(lines[j].lstrip())]
                payload = json.dumps(desc, ensure_ascii=False)
                tail = ""
                stripped = lines[j].rstrip()
                if stripped.endswith(","):
                    tail = ","
                lines[j] = "%s\"desc\": %s%s" % (indent, payload, tail)
                done = True
                changed += 1
                break
        if not done:
            missing.append(iid + "(desc 没找到)")

    # ── ② 追加 30 件新道具（id 已存在就跳过）──
    added = 0
    blocks = []
    for row in NEW_ITEMS:
        if row["id"] in have:
            continue
        blocks.append(format_item_block(row))
        added += 1
    new_text = "\n".join(lines)
    if blocks:
        anchor = new_text.rindex("\n  ]")               # items 数组的收尾
        before = new_text[:anchor].rstrip()
        if not before.endswith(","):
            before += ","                               # 上一行 `}` 后面要补一个逗号
        new_text = before + "\n\n" + ",\n\n".join(blocks) + new_text[anchor:]

    # ── ③ 校验（改完之后必须仍是合法 JSON，且条数对得上）──
    check = json.loads(new_text)
    old_n, new_n = len(table["items"]), len(check["items"])
    if new_n != old_n + added:
        print("FAIL count: %d -> %d (expected +%d)" % (old_n, new_n, added))
        return 1
    ids = [it["id"] for it in check["items"]]
    if len(set(ids)) != len(ids):
        print("FAIL duplicate ids")
        return 1
    for it in check["items"]:
        for b in it.get("effects", []) + it.get("costs", []):
            if not isinstance(b.get("add"), (int, float)):
                print("FAIL bad bonus in " + it["id"])
                return 1

    print("desc rewritten: %d | new items: %d | total %d" % (changed, added, new_n))
    if missing:
        print("missing ids: " + ", ".join(missing))
    if dry:
        print("(dry-run: 未写盘)")
        return 0
    write_text(ITEMS, new_text, bom)
    print("written: %s (bom=%s)" % (os.path.relpath(ITEMS, ROOT), bom))
    return 0


def format_item_block(row):
    """按本表既有排版输出一件道具（字段顺序与手写行一致）。"""
    out = []
    head = ('    { "id": "%s", "name": "%s", "grade": "%s", "category": %d, '
            '"price": %d, "maxStack": %d,'
            % (row["id"], row["name"], row["grade"], row["category"],
               row["price"], row["maxStack"]))
    out.append(head)
    out.append('      "desc": %s,' % json.dumps(row["desc"], ensure_ascii=False))
    if row.get("effects"):
        out.append('      "effects": [ %s ]%s'
                   % (", ".join(json.dumps(b, ensure_ascii=False) for b in row["effects"]),
                      "," if row.get("costs") else " }"))
    if row.get("costs"):
        out.append('      "costs":   [ %s ] }'
                   % ", ".join(json.dumps(b, ensure_ascii=False) for b in row["costs"]))
    return "\n".join(out)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
