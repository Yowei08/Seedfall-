#!/usr/bin/env python3
"""gen_v180_fx_meshes.py —— 生成 v180 两种新特效网格的**离线同源副本**。

为什么要有这个文件
------------------
运行时构造在 `Assets/Scripts/Bootstrap/WorldView.cs`（`FxBladeMesh` / `FxRingMesh`）。
那份代码是**唯一能被 Unity 编译**的地方（`Tools/` 在 `Assets/` 之外，见
`WorldView.cs:2521` 那段"为什么运行时构造写在本文件"的记录）。

但"能编译"不等于"能被核对"：顶点数、三角数、环宽这些量写在 C# 里，
改一个数字没有任何东西会失败。所以这个脚本按**同一套参数**重建同样的拓扑，
落成 OBJ 预览 + 清单，并在 `--check` 下与 C# 侧钉住的常量**逐项比对**。

约定（与 `gen_fx_meshes.py` / `verify_counts.py` 同一套）
--------------------------------------------------------
· 全部 **flat shading**：每个三角形独占 3 个顶点 ⇒ `顶点数 = 三角数 × 3`
· 全部 **双面**：每个四边形正反各发两遍 ⇒ `三角数 = 四边形数 × 4`

用法
----
    python Tools/mesh_gen/gen_v180_fx_meshes.py          # 生成 out/fx_blade.obj 等
    python Tools/mesh_gen/gen_v180_fx_meshes.py --check   # 只核对常量，不写文件
"""

import argparse
import json
import math
import os
import sys

# Windows 控制台默认是 GBK，`⇒` / `×` 这些东西会直接抛 UnicodeEncodeError 把脚本打断。
# 统一按 UTF-8 输出：终端可能显示成乱码，但**不会**因为一个符号让生成脚本失败。
try:
    sys.stdout.reconfigure(encoding="utf-8")
except Exception:
    pass

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")

# ── 与 WorldView.cs 逐字对应的参数（改一边必须改另一边）──────────────────────
BLADE = {
    "segs": 20,          # WorldView.FxBladeMesh: const int segs = 20
    "inner": 0.62,       # const float inner = 0.62f
    "outer": 1.00,       # const float outer = 1.0f
    "thick_in": 0.055,   # const float thickIn = 0.055f
    "thick_out": 0.004,  # const float thickOut = 0.004f
    "half_deg": 55.0,    # const float halfDeg = 55f
    "quads_per_seg": 4,  # 上面 / 下面 / 内缘 / 刃口
}
RING = {
    "segs": 36,          # WorldView.SpawnGroundRim: FxRingMesh(5600, 36, 0.86f)
    "inner_ratio": 0.86,
    "quads_per_seg": 1,
}
SHOCK_RING = {
    "segs": 30,          # WorldView.SpawnShockRing: FxRingMesh(5610, 30, 0.86f)
    "inner_ratio": 0.86,
    "quads_per_seg": 1,
}


def quad_count_blade():
    return BLADE["segs"] * BLADE["quads_per_seg"]


def tris_of(quads):
    return quads * 4          # 双面：每个四边形 2 三角 × 2


def blade_vertices():
    """刃形的三角汤（每个四边形 → 4 个三角 → 12 个顶点）。"""
    b = BLADE
    verts = []

    def section(ang):
        s, c = math.sin(ang), math.cos(ang)
        i, o, ti, to = b["inner"], b["outer"], b["thick_in"], b["thick_out"]
        return [
            (s * i,  ti, c * i),     # 0 内上（刀背）
            (s * o,  to, c * o),     # 1 外上（刃口）
            (s * o, -to, c * o),     # 2 外下
            (s * i, -ti, c * i),     # 3 内下
        ]

    def quad(a, bb, c, d):
        verts.extend([a, bb, c, a, c, d])
        verts.extend([a, c, bb, a, d, c])     # 反向（双面）

    for i in range(b["segs"]):
        a0 = math.radians(-b["half_deg"] + (2 * b["half_deg"]) * (i / b["segs"]))
        a1 = math.radians(-b["half_deg"] + (2 * b["half_deg"]) * ((i + 1) / b["segs"]))
        p0, p1 = section(a0), section(a1)
        quad(p0[0], p1[0], p1[1], p0[1])      # 上面
        quad(p0[3], p1[3], p1[2], p0[2])      # 下面
        quad(p0[0], p1[0], p1[3], p0[3])      # 内缘
        quad(p0[1], p1[1], p1[2], p0[2])      # 刃口
    return verts


def ring_vertices(conf):
    verts = []
    for i in range(conf["segs"]):
        t0 = (i / conf["segs"]) * math.tau
        t1 = ((i + 1) / conf["segs"]) * math.tau
        o0 = (math.cos(t0), 0.0, math.sin(t0))
        o1 = (math.cos(t1), 0.0, math.sin(t1))
        i0 = tuple(v * conf["inner_ratio"] for v in o0)
        i1 = tuple(v * conf["inner_ratio"] for v in o1)
        verts.extend([i0, o0, o1, i0, o1, i1])
        verts.extend([i0, o1, o0, i0, i1, o1])    # 反向（双面）
    return verts


def write_obj(path, verts, name):
    # OBJ 的注释也用 ASCII：文件头写着它怎么来的，用英文即可，避免编码坑
    title = "FxBlade" if "Blade" in name else ("FxRing36" if "36" in name else "FxRing30")
    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write(f"# {title} - generated by Tools/mesh_gen/gen_v180_fx_meshes.py\n")
        handle.write(f"# {len(verts)} verts / {len(verts)//3} tris (flat + double sided)\n")
        for v in verts:
            handle.write(f"v {v[0]:.6f} {v[1]:.6f} {v[2]:.6f}\n")
        for i in range(0, len(verts), 3):
            handle.write(f"f {i+1} {i+2} {i+3}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    blade_tris = tris_of(quad_count_blade())
    ring_tris = tris_of(RING["segs"] * RING["quads_per_seg"])
    shock_tris = tris_of(SHOCK_RING["segs"] * SHOCK_RING["quads_per_seg"])

    rows = [
        ("fx_blade", blade_tris, quad_count_blade()),
        ("fx_ring36", ring_tris, RING["segs"]),
        ("fx_ring30", shock_tris, SHOCK_RING["segs"]),
    ]
    print("网格          四边形  三角   顶点   （flat ⇒ 顶点 = 三角×3）")
    for name, tris, quads in rows:
        print(f"{name:<12}{quads:>7}{tris:>7}{tris*3:>7}")

    if args.check:
        # 与 C# 侧钉住的常量比对：20 段 × 4 面 × 4 三角 = 320
        assert blade_tris == 320, f"刃形三角数应为 320，实为 {blade_tris}"
        assert ring_tris == 144, f"36 段细环三角数应为 144，实为 {ring_tris}"
        assert shock_tris == 120, f"30 段细环三角数应为 120，实为 {shock_tris}"
        print("核对通过：与 WorldView.cs 里的常量一致")
        return 0

    os.makedirs(OUT, exist_ok=True)
    blade = blade_vertices()
    write_obj(os.path.join(OUT, "fx_blade.obj"), blade, "FxBlade(刃形, 有厚度)")
    write_obj(os.path.join(OUT, "fx_ring36.obj"), ring_vertices(RING), "FxRing(36 段细环)")
    write_obj(os.path.join(OUT, "fx_ring30.obj"), ring_vertices(SHOCK_RING), "FxRing(30 段细环)")

    manifest = {
        "generator": "Tools/mesh_gen/gen_v180_fx_meshes.py",
        "runtime_source": "Assets/Scripts/Bootstrap/WorldView.cs",
        "runtime_functions": ["FxBladeMesh", "FxRingMesh", "Quad"],
        "shading": "flat（每面拆顶点）+ 双面（每四边形正反各发一遍）",
        "meshes": {
            "fx_blade": {"quads": quad_count_blade(), "tris": blade_tris,
                         "verts": blade_tris * 3, "params": BLADE},
            "fx_ring36": {"quads": RING["segs"], "tris": ring_tris,
                          "verts": ring_tris * 3, "params": RING},
            "fx_ring30": {"quads": SHOCK_RING["segs"], "tris": shock_tris,
                          "verts": shock_tris * 3, "params": SHOCK_RING},
        },
        "purpose": {
            "fx_blade": "锄头挥击的刃形（替掉原来的扇形面片 ArcMesh）",
            "fx_ring36": "地面边界圈 / 肥料前摇环（替掉填充圆盘）",
            "fx_ring30": "插件冲击环 / 水柱命中环（替掉实心圆柱）",
        },
    }
    with open(os.path.join(OUT, "fx_v180_manifest.json"), "w", encoding="utf-8", newline="\n") as handle:
        json.dump(manifest, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
    print(f"已写出 3 个 OBJ + fx_v180_manifest.json → {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
